"""Write the tool table in PROMPT.md from the @tool docstrings, so the brief cannot drift from the code.

python harness/mcp/tool_table.py           rewrite the block between the tools:begin/end markers
python harness/mcp/tool_table.py --check   exit 1 if the block is out of date
Run it after adding, removing or re-describing a tool. It parses source; nothing is imported or connected.
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROMPT, TOOLS = ROOT / "PROMPT.md", ROOT / "harness" / "tools"
BEGIN, END = "<!-- tools:begin (generated by harness/mcp/tool_table.py; do not edit by hand) -->", "<!-- tools:end -->"


def summary(doc: str, limit: int = 170) -> str:
    """First sentence of the first paragraph, on one line."""
    text = " ".join((doc or "").split("\n\n")[0].split())
    text = re.split(r"(?<=[.])\s", text, maxsplit=1)[0].rstrip(".:;,")
    return (text if len(text) <= limit else text[:limit - 1].rstrip() + "…").replace("|", "/")


def table() -> str:
    out = []
    for path in sorted(TOOLS.glob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        tools = [n for n in tree.body if isinstance(n, ast.FunctionDef)
                 and any(getattr(getattr(d, "func", d), "id", "") == "tool" for d in n.decorator_list)]
        if not tools: continue
        out += [f"**`harness/tools/{path.name}`**: {summary(ast.get_docstring(tree), 300)}.", "", "| Tool | What it does |", "| --- | --- |"]
        out += [f"| `{n.name}` | {summary(ast.get_docstring(n))} |" for n in tools] + [""]
    return "\n".join(out).rstrip()


def render(prompt: str) -> str:
    if BEGIN not in prompt or END not in prompt: raise SystemExit("PROMPT.md has no tools:begin/tools:end markers")
    head, rest = prompt.split(BEGIN, 1)
    return f"{head}{BEGIN}\n{table()}\n{END}{rest.split(END, 1)[1]}"


if __name__ == "__main__":
    current = PROMPT.read_text(encoding="utf-8")
    fresh = render(current)
    if "--check" in sys.argv[1:]:
        sys.exit("PROMPT.md tool table is out of date: run python harness/mcp/tool_table.py" if fresh != current else 0)
    PROMPT.write_bytes(fresh.encode("utf-8"))
    print(f"PROMPT.md tool table: {table().count('| `mb_')} tools")
